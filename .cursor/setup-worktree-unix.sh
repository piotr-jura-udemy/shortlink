#!/usr/bin/env bash
# Cursor worktree setup for shortlink (macOS / Linux).
# Runs from the new worktree root. ROOT_WORKTREE_PATH points at the primary checkout.
set -euo pipefail

echo "==> shortlink worktree setup"

if [[ ! -f package.json ]]; then
  echo "error: expected to run from the worktree root (package.json missing)" >&2
  exit 1
fi

echo "==> installing dependencies"
npm ci

# Per-worktree SQLite file — never reuse or copy the primary checkout's DB.
DB_FILE="sqlite.worktree.db"
export SQLITE_PATH="${DB_FILE}"

echo "==> writing .env.local (SQLITE_PATH=${SQLITE_PATH})"
{
  echo "# Generated by .cursor/setup-worktree-unix.sh — do not commit"
  echo "SQLITE_PATH=${SQLITE_PATH}"
  echo "BETTER_AUTH_SECRET=worktree-dev-secret-at-least-32-chars"
  echo "BETTER_AUTH_URL=http://localhost:3000"
} > .env.local

# Carry over any extra env from the primary checkout (except SQLITE_PATH).
if [[ -n "${ROOT_WORKTREE_PATH:-}" ]]; then
  for candidate in .env.local .env; do
    src="${ROOT_WORKTREE_PATH}/${candidate}"
    if [[ -f "${src}" ]]; then
      echo "==> merging non-SQLITE vars from ${candidate} in primary checkout"
      while IFS= read -r line || [[ -n "${line}" ]]; do
        [[ -z "${line}" || "${line}" =~ ^[[:space:]]*# ]] && continue
        key="${line%%=*}"
        [[ "${key}" == "SQLITE_PATH" ]] && continue
        if ! grep -q "^${key}=" .env.local 2>/dev/null; then
          echo "${line}" >> .env.local
        fi
      done < "${src}"
      break
    fi
  done
fi

echo "==> resetting worktree database"
rm -f "${DB_FILE}" "${DB_FILE}-wal" "${DB_FILE}-shm"

echo "==> running migrations"
npm run db:migrate

echo "==> seeding sample links"
npm run db:seed

# Shared browser cache; cheap if already installed.
if [[ -d e2e ]] && grep -q playwright package.json 2>/dev/null; then
  echo "==> ensuring Playwright Chromium is available"
  npx playwright install chromium
fi

echo "==> worktree ready"
echo "    SQLITE_PATH=${SQLITE_PATH}"
echo "    Start with: npm run dev"
